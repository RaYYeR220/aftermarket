import { spawn, type ChildProcess } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";

export interface AnvilOptions {
  readonly forkUrl: string;
  readonly forkBlockNumber?: bigint | undefined;
  readonly port: number;
  readonly timeoutMs?: number;
}

export interface AnvilHandle {
  readonly rpcUrl: string;
  readonly pid: number | undefined;
  stop(): void;
}

/**
 * How the eval found an anvil that can execute Coinbase's B20 tokens.
 *
 * Stock anvil cannot: the B20 assets on Base are Rust precompiles rather than deployed Solidity, so
 * `eth_getCode` returns `0xef` for them and a vanilla EVM has nothing to run. Base's `base-anvil`
 * ships those precompiles, which is why the eval requires it.
 */
export interface AnvilBinary {
  readonly command: string;
  /**
   * Whether `--base` has to be supplied by us. The `base-anvil` wrapper adds it; the underlying
   * `anvil` binary the wrapper calls does not.
   */
  readonly needsBaseFlag: boolean;
  readonly source: string;
}

/**
 * Locates a `base-anvil` this platform can actually spawn.
 *
 * On Windows the installed `base-anvil` is a bash wrapper with no extension, which `spawn` cannot
 * execute; the wrapper's one job is to exec `<foundry>/versions/<v>/anvil.exe --base`, so the
 * launcher reads the path back out of it and calls that directly. Everywhere else the wrapper is a
 * normal executable script and is used as-is. `ANVIL_BIN` overrides the search entirely.
 */
export function resolveAnvilBinary(): AnvilBinary {
  const override = process.env["ANVIL_BIN"]?.trim();
  if (override) {
    return {
      command: override,
      needsBaseFlag: !/base-anvil/i.test(override),
      source: "ANVIL_BIN",
    };
  }

  const wrapper = join(homedir(), ".foundry", "bin", "base-anvil");
  if (existsSync(wrapper)) {
    if (process.platform !== "win32") {
      return { command: wrapper, needsBaseFlag: false, source: wrapper };
    }
    const inner = readAnvilPathFromWrapper(wrapper);
    if (inner) return { command: inner, needsBaseFlag: true, source: `${wrapper} → ${inner}` };
  }

  throw new Error(
    "could not find base-anvil. Install Base's Foundry fork (base-foundryup) or set ANVIL_BIN to an " +
      "anvil binary that ships the B20 precompiles. Stock anvil cannot execute Coinbase's tokenized " +
      "stocks, because they are Rust precompiles rather than deployed bytecode.",
  );
}

/**
 * Pulls the real `anvil` path out of the shell wrapper Base's installer writes.
 *
 * The wrapper is generated by `foundryup --network base` and its body is a single `exec` of the
 * versioned binary. On Windows the path inside it is written in MSYS form (`/c/Users/…`) and
 * without the `.exe` suffix, because the wrapper is meant to be read by bash rather than by
 * `CreateProcess` — so both have to be translated back before `spawn` will accept it.
 */
function readAnvilPathFromWrapper(wrapper: string): string | null {
  let contents: string;
  try {
    contents = readFileSync(wrapper, "utf8");
  } catch {
    return null;
  }

  const match = /["']?((?:[A-Za-z]:|\/[A-Za-z])[\\/][^\s"']*?anvil(?:\.exe)?)["']?/.exec(contents);
  if (!match?.[1]) return null;

  let candidate = match[1].replaceAll("\\", "/");
  // `/c/Users/…` is how MSYS spells `C:/Users/…`.
  const msys = /^\/([A-Za-z])\//.exec(candidate);
  if (msys?.[1]) candidate = `${msys[1].toUpperCase()}:/${candidate.slice(3)}`;

  for (const path of [candidate, `${candidate}.exe`]) {
    if (existsSync(path)) return path;
  }
  return null;
}

/**
 * Starts a local fork of Base mainnet and resolves once it answers `eth_chainId`.
 *
 * `--auto-impersonate` is on because the eval drives contracts as their owner and as third-party
 * repayers; nothing about the keeper under test uses impersonation. The process is killed on exit
 * of the parent too, so an interrupted run never leaves a node holding a port.
 */
export async function startAnvil(options: AnvilOptions): Promise<AnvilHandle> {
  const binary = resolveAnvilBinary();
  const args = [
    ...(binary.needsBaseFlag ? ["--base"] : []),
    "--fork-url",
    options.forkUrl,
    "--port",
    String(options.port),
    "--auto-impersonate",
    "--silent",
  ];
  if (options.forkBlockNumber !== undefined) {
    args.push("--fork-block-number", options.forkBlockNumber.toString());
  }

  const child: ChildProcess = spawn(binary.command, args, {
    env: { ...process.env, FOUNDRY_BASE: "true" },
    stdio: ["ignore", "pipe", "pipe"],
    windowsHide: true,
  });

  let stderr = "";
  child.stderr?.on("data", (chunk: Buffer) => {
    stderr += chunk.toString();
  });
  let exited = false;
  child.on("exit", () => {
    exited = true;
  });

  const rpcUrl = `http://127.0.0.1:${options.port}`;
  const stop = (): void => {
    if (!child.killed) child.kill();
  };
  const onParentExit = (): void => stop();
  process.once("exit", onParentExit);

  const deadline = Date.now() + (options.timeoutMs ?? 60_000);
  for (;;) {
    if (exited) {
      process.removeListener("exit", onParentExit);
      throw new Error(`${binary.source} exited before it was ready:\n${stderr.trim() || "(no output)"}`);
    }
    if (await isReady(rpcUrl)) break;
    if (Date.now() > deadline) {
      stop();
      process.removeListener("exit", onParentExit);
      throw new Error(`${binary.source} did not become ready in time:\n${stderr.trim() || "(no output)"}`);
    }
    await new Promise((resolve) => setTimeout(resolve, 150));
  }

  return {
    rpcUrl,
    pid: child.pid,
    stop: () => {
      process.removeListener("exit", onParentExit);
      stop();
    },
  };
}

async function isReady(rpcUrl: string): Promise<boolean> {
  try {
    const response = await fetch(rpcUrl, {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "eth_chainId", params: [] }),
    });
    if (!response.ok) return false;
    const body = (await response.json()) as { result?: string };
    return typeof body.result === "string";
  } catch {
    return false;
  }
}
